"""Build a readable codebook from editable taxonomy, values and definitions."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
def read(p): return json.loads((ROOT/p).read_text(encoding="utf-8"))

def build():
    taxonomy=read("config/v2/taxonomy.json");vocab=read("config/v2/vocabulary.json");guide=read("config/v2/label-guide.json")
    ids=[d["id"] for d in taxonomy["domains"]]
    if len(ids)!=len(set(ids)) or set(ids)!=set(guide["domain_definitions"]): raise ValueError("Domain IDs/definitions mismatch")
    topics=[t["id"] for t in taxonomy["topics"]]
    if len(topics)!=len(set(topics)): raise ValueError("Duplicate topic IDs")
    for t in taxonomy["topics"]:
        if not t["definition"].strip() or not t["routing_rule"].strip() or not t["domain_ids"] or not set(t["domain_ids"])<=set(ids): raise ValueError(f"Invalid topic: {t['id']}")
    dimensions={d["id"]:d for d in guide["dimensions"]}
    expected={k for k,v in vocab.items() if isinstance(v,list)}
    if set(dimensions)!=expected or len(dimensions)!=len(guide["dimensions"]):raise ValueError("Label dimension/guide mismatch")
    for key in expected:
        values=vocab[key];options=dimensions[key]["options"]
        if not values or len(values)!=len(set(values)) or [o["id"] for o in options]!=values:raise ValueError(f"Guide options differ from vocabulary: {key}")
        if any(not o["definition"].strip() or not o["label"].strip() for o in options):raise ValueError(f"Missing definition in {key}")
    return {**guide,"domains":[{**d,"definition":guide["domain_definitions"][d["id"]]} for d in taxonomy["domains"]],"topics":taxonomy["topics"],"taxonomy_version":taxonomy['version'],"vocabulary_version":vocab["version"]}

def main():
    data=build();(ROOT/"integrations/fixtures/knowledge.json").write_text(json.dumps(data,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    lines=["# Knowledge structure and labeling guide", "", "Generated by scripts/build_knowledge.py from config/v2/taxonomy.json, vocabulary.json and label-guide.json. Edit those sources, not this file.", "", data["status"], "", data["scope"], "", "## Record structure", ""]
    lines += [f"- **{r['name']}:** {r['meaning']}" for r in data["record_structure"]]
    lines += ["", "## Domains and topics", "", "A domain is a sector; a topic is the only subdomain level. Select supported topic IDs; the application derives their domains. Cross-domain topics do not create duplicate commitments.", ""]
    for d in data["domains"]:
        lines += [f"### {d['name']} (`{d['id']}`)","",d["definition"],"", "| Topic | Meaning | Assignment rule |", "|---|---|---|"]
        lines += [f"| {t['id']} — {t['name']} | {t['definition']} | {t['routing_rule']} |" for t in data["topics"] if d["id"] in t["domain_ids"]]
        lines += [""]
    category = None
    for d in sorted(data["dimensions"], key=lambda d: ["policy", "detail", "evidence"].index(d.get("category", "detail"))):
        if d.get("category", "detail") != category:
            category = d.get("category", "detail")
            lines += ["# " + {"policy": "Policy labels", "detail": "Linked facts and details", "evidence": "Evidence and processing information"}[category], ""]
        lines += [f"## {d['label']} (`{d['id']}`)","",d["question"],"",d["rule"],"", "| Value | Meaning |", "|---|---|"]
        lines += [f"| `{o['id']}` — {o['label']} | {o['definition']} |" for o in d["options"]]
        lines += [""]
    lines += ["## Unmapped terms and changes", "", "Keep irrelevant facets empty. If a relevant concept has no fitting option, preserve the source term and evidence in unmapped_terms. Do not force it into a default sector or invent a permanent ID. Edit the versioned taxonomy/vocabulary and guide, validate and rebuild; new runs use the new configuration. Existing reports retain their original method versions.","", "## References", ""]
    lines += [f"- [{r['title']}]({r['url']}): {r['use']}" for r in data["references"]]
    (ROOT/"docs/knowledge/labeling-guide.md").write_text("\n".join(lines)+"\n",encoding="utf-8")
    print(f"Built {len(data['domains'])} domains, {len(data['topics'])} topics, {len(data['dimensions'])} label dimensions and {sum(len(d['options']) for d in data['dimensions'])} defined values.")

if __name__=="__main__":main()
